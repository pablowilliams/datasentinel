"""The approval model being monitored.

Deliberately a plain logistic regression. The project is about whether the
platform notices a model going wrong, and a model whose coefficients can be read
makes it obvious when something has changed. A gradient-boosted ensemble would
score better and explain less.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from datasentinel.model.features import (
    CATEGORICAL,
    FEATURES,
    LABEL,
    NUMERIC,
    check_no_leakage,
)


@dataclass(frozen=True)
class ModelCard:
    name: str
    version: str
    trained_at: str
    train_rows: int
    train_window: tuple[str, str]
    features: list[str]
    excluded_as_post_decision: list[str]
    note: str


def build_features(frame: pd.DataFrame) -> pd.DataFrame:
    """Decision-time features only, with the affordability ratio added."""
    missing = [c for c in FEATURES if c not in frame.columns]
    if missing:
        raise ValueError(f"cannot score: features absent from the batch: {', '.join(missing)}")

    designed = frame[list(FEATURES)].copy()
    income = pd.to_numeric(frame["annual_income"], errors="coerce")
    loan = pd.to_numeric(frame["loan_amount"], errors="coerce")
    designed["loan_to_income"] = loan / income.where(income > 0)
    check_no_leakage(list(designed.columns))
    return designed


def make_pipeline() -> Pipeline:
    numeric = [*NUMERIC, "loan_to_income"]
    return Pipeline(
        [
            (
                "prepare",
                ColumnTransformer(
                    [
                        (
                            "numeric",
                            Pipeline(
                                [
                                    # Real batches arrive with gaps; a model that
                                    # cannot score an incomplete row cannot run.
                                    ("impute", SimpleImputer(strategy="median")),
                                    ("scale", StandardScaler()),
                                ]
                            ),
                            numeric,
                        ),
                        (
                            "categorical",
                            Pipeline(
                                [
                                    ("impute", SimpleImputer(strategy="most_frequent")),
                                    # Unseen categories must not crash scoring. A
                                    # new employment type is the drift module's
                                    # problem to report, not the model's to die on.
                                    ("encode", OneHotEncoder(handle_unknown="ignore")),
                                ]
                            ),
                            list(CATEGORICAL),
                        ),
                    ]
                ),
            ),
            ("model", LogisticRegression(max_iter=2_000, C=1.0)),
        ]
    )


def train(frame: pd.DataFrame, *, version: str) -> tuple[Pipeline, ModelCard]:
    labelled = frame.dropna(subset=[LABEL])
    pipeline = make_pipeline()
    pipeline.fit(build_features(labelled), labelled[LABEL].astype(bool))

    dates = pd.to_datetime(labelled["application_date"], errors="coerce")
    card = ModelCard(
        name="approval_classifier",
        version=version,
        trained_at=datetime.now(UTC).isoformat(timespec="seconds"),
        train_rows=len(labelled),
        train_window=(str(dates.min().date()), str(dates.max().date())),
        features=list(build_features(labelled).columns),
        excluded_as_post_decision=["interest_rate"],
        note=(
            "Logistic regression on synthetic data whose label was generated by a "
            "logistic function. High discrimination here reflects the generator, "
            "not model skill, and the figure to watch is how it moves under drift "
            "rather than its level."
        ),
    )
    return pipeline, card


def save(pipeline: Pipeline, card: ModelCard, directory: Path) -> Path:
    import pickle

    directory.mkdir(parents=True, exist_ok=True)
    target = directory / f"{card.name}-{card.version}.pkl"
    target.write_bytes(pickle.dumps(pipeline))
    (directory / f"{card.name}-{card.version}.json").write_text(json.dumps(asdict(card), indent=2))
    return target


def load(directory: Path, name: str, version: str) -> tuple[Pipeline, ModelCard]:
    import pickle

    pipeline = pickle.loads((directory / f"{name}-{version}.pkl").read_bytes())
    payload = json.loads((directory / f"{name}-{version}.json").read_text())
    # JSON has no tuples, so the declared type has to be restored or a loaded
    # card silently differs from the one that was saved.
    payload["train_window"] = tuple(payload["train_window"])
    card = ModelCard(**payload)
    return pipeline, card
